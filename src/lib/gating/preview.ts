import 'server-only';

/**
 * «Просмотр от лица тира» — админ смотрит портал глазами бесплатного пользователя,
 * чтобы проверить пейволы, не заводя фейковых аккаунтов и не трогая боевые гейты.
 * Нужен потому, что отдельной dev-базы у проекта нет: локальная разработка ходит в ту
 * же БД, что и прод (CLAUDE.md §4.13), и «поправить порог, чтобы посмотреть» означало
 * бы мигнуть замками живым пользователям.
 *
 * 🔒 ДВА ПРАВИЛА БЕЗОПАСНОСТИ, оба обязательны:
 *  1. Превью только ПОНИЖАЕТ видимый ранг (min с реальным). Поднять себе доступ им
 *     нельзя — иначе это готовый вектор эскалации прав через одну куку.
 *  2. Право проверяется через getAdmin() (роль + AAL2), а не по наличию куки.
 *
 * Реальную подписку превью НЕ меняет: живёт в куке сессии, в БД не пишется.
 */

import { cookies } from 'next/headers';
import { getAdmin } from '@/lib/auth/admin';

/** Имя куки. Сессионная (без maxAge) — закрыл вкладку, вышел из превью. */
export const TIER_PREVIEW_COOKIE = 'cta_tier_preview';

/**
 * Слаг тира, от лица которого смотрит текущий пользователь, или null.
 *
 * Быстрый выход, если куки нет — а её нет практически всегда. Это важно: функция зовётся
 * из resolveEntitlements, то есть на КАЖДОМ рендере страницы, а getAdmin() ходит в БД.
 * Без этой проверки мы бы добавили лишний запрос к профилю на каждый рендер портала.
 *
 * ⚠️ cookies() НЕ оборачиваем в try/catch: Next сигнализирует о переходе рендера в
 * динамику исключением, и «на всякий случай» проглоченный catch ломает этот механизм.
 * Вызывающий (resolveEntitlements) всегда работает в request-скоупе.
 */
export async function getPreviewTierSlug(): Promise<string | null> {
  const slug = (await cookies()).get(TIER_PREVIEW_COOKIE)?.value?.trim();
  if (!slug) return null;

  // Кука есть — только теперь платим за проверку роли. Не админ → превью игнорируется.
  const admin = await getAdmin();
  if (!admin) return null;

  return slug;
}
