/** Год → события (для рельсы годов). Сортировку задаёт UI. */
export function getEventYears(events: EftEvent[]): number[] {
  const years = new Set<number>();
  for (const e of events) years.add(Number(e.date.slice(0, 4)));
  return [...years].sort((a, b) => b - a);
}

export function getCategoryMeta(id: EftEventCategory): EftEventCategoryMeta {
  const found = EFT_EVENT_CATEGORIES.find((c) => c.id === id);
  // Реестр покрывает все значения union — фолбэк только для типобезопасности.
  return found ?? { id, label: id, hint: '' };
}
